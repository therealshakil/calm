#!/usr/bin/env python3
"""Build calm-fonts.css — self-contained base64 @font-face rules for the calm faces, so any artifact
can inline the *real* faces past the sandbox CSP (which blocks font CDNs).

Source woff2 live in assets/fonts/ (OFL, latin subset). Add a face/weight by dropping its woff2 in and
adding a line to FACES, then re-run: `python3 scripts/build-calm-fonts.py`.
"""
import base64
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FD = ROOT / "assets" / "fonts"
OUT = ROOT / "calm-fonts.css"

# (css font-family — must match tokens.css names, weight, filename in assets/fonts/)
FACES = [
    ("Atkinson Hyperlegible", 400, "atkinson-400.woff2"),
    ("Atkinson Hyperlegible", 700, "atkinson-700.woff2"),
    ("Yrsa", 600, "yrsa-600.woff2"),
    ("Shantell Sans", 400, "shantell-400.woff2"),
    ("IBM Plex Mono", 400, "ibm-plex-mono-400.woff2"),
]


def rule(family: str, weight: int, filename: str) -> str:
    b64 = base64.b64encode((FD / filename).read_bytes()).decode("ascii")
    return (
        f"@font-face{{font-family:'{family}';font-style:normal;font-weight:{weight};"
        f"font-display:swap;src:url(data:font/woff2;base64,{b64}) format('woff2');}}"
    )


def main() -> None:
    header = (
        "/* calm-ds fonts — self-contained data-URIs (OFL, latin subset). Inline into any artifact's\n"
        "   <style> so the real calm faces render past the CSP. Generated by scripts/build-calm-fonts.py. */\n"
    )
    OUT.write_text(header + "\n".join(rule(*f) for f in FACES) + "\n")
    print(f"wrote {OUT} ({round(OUT.stat().st_size / 1024)} KB, {len(FACES)} faces)")


if __name__ == "__main__":
    main()
